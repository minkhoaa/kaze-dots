]],
        cfg.font,
        cfg.terminal,
        cfg.cursor_theme,
        radius,
        themes.hex_alpha(theme.bg_alt, "e8"),
        themes.hex_alpha(theme.fg, "ff"),
        themes.hex_alpha(theme.accent, "ff"),
        themes.hex_alpha(theme.fg_muted, "ff"),
        themes.hex_alpha(theme.fg, "ff"),
        themes.hex_alpha(theme.accent, "ff"),
        themes.hex_alpha(theme.surface, "ff"),
        themes.hex_alpha(theme.fg, "ff"),
        themes.hex_alpha(theme.accent, "ff"),
        themes.hex_alpha(theme.border, "dd")
