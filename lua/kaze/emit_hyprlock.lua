local themes = require("kaze.themes")

local M = {}

function M.emit(cfg, theme, layout)
    local wallpaper = cfg.wallpaper_expanded or cfg.wallpaper or ""
    local rounding = math.max(0, math.min(layout.hypr.rounding, 16))
    local is_light = themes.is_light(theme)
    local bg_brightness = is_light and "0.85" or "0.65"
    local light_card = ""
    local bottom_shadow = ""
    if is_light then
        -- Frosted sharp backing panel keeps dark ink readable over any wallpaper in light mode.
        light_card = string.format([[
shape {
    monitor =
    size = 380, 290
    color = %s
    rounding = %d
    border_size = 2
    border_color = %s
    position = 0, 20
    halign = center
    valign = center
    zindex = 0
}
]], themes.hypr_rgba(theme.bg_alt, "e8"), rounding, themes.hypr_rgb(theme.border))
        bottom_shadow = string.format([[
    shadow_passes = 2
    shadow_size = 4
    shadow_color = %s
    shadow_boost = 1.6]], themes.hypr_rgb(theme.bg))
    end
    return string.format([[# Auto-generated by kaze-sync — DO NOT EDIT MANUALLY (edit ~/.config/kaze/user.lua)
general {
    hide_cursor = true
    ignore_empty_input = true
    immediate_render = true
}

background {
    monitor =
    path = %s
    color = %s
    blur_passes = 2
    blur_size = 5
    brightness = %s
}
%s
label {
    monitor =
    text = $TIME
    color = %s
    font_size = 68
    font_family = %s Bold
    position = 0, 90
    halign = center
    valign = center
    zindex = 1
}

label {
    monitor =
    text = cmd[update:60000] date +"%%A, %%d %%B"
    color = %s
    font_size = 15
    font_family = %s
    position = 0, 22
    halign = center
    valign = center
    zindex = 1
}

input-field {
    monitor =
    size = 300, 46
    outline_thickness = 2
    dots_size = 0.24
    dots_spacing = 0.25
    outer_color = %s
    inner_color = %s
    font_color = %s
    fade_on_empty = true
    placeholder_text = <i>Password...</i>
    rounding = %d
    check_color = %s
    fail_color = %s
    capslock_color = %s
    position = 0, -60
    halign = center
    valign = center
    zindex = 1
}

label {
    monitor =
    text = cmd[update:15000] sh -c 'out=""; for b in /sys/class/power_supply/BAT*/capacity; do if [ -r "$b" ]; then c=$(cat "$b"); d=$(dirname "$b"); s=$(cat "$d/status" 2>/dev/null); p=""; [ "$s" = Charging ] && p="+"; out="󰁹 $c%%$p"; break; fi; done; if command -v playerctl >/dev/null 2>&1 && [ "$(playerctl status 2>/dev/null)" = Playing ]; then t=$(playerctl metadata xesam:title 2>/dev/null | tr -d "\r\n\\<>&" | cut -c1-40); a=$(playerctl metadata xesam:artist 2>/dev/null | tr -d "\r\n\\<>&" | cut -c1-24); if [ -n "$t" ]; then m="󰎈 $t"; [ -n "$a" ] && m="󰎈 $a — $t"; if [ -n "$out" ]; then out="$out  ·  $m"; else out="$m"; fi; fi; fi; echo "$out"'
    color = %s
    font_size = 12
    font_family = %s
    position = 0, 36
    halign = center
    valign = bottom
    zindex = 1%s
}
]],
        wallpaper,
        themes.hypr_rgb(theme.bg),
        bg_brightness,
        light_card,
        themes.hypr_rgb(theme.fg),
        cfg.font,
        themes.hypr_rgb(theme.fg_muted),
        cfg.font,
        themes.hypr_rgb(theme.accent),
        themes.hypr_rgb(theme.bg_alt),
        themes.hypr_rgb(theme.fg),
        rounding,
        themes.hypr_rgb(theme.ok),
        themes.hypr_rgb(theme.danger),
        themes.hypr_rgb(theme.warn),
        themes.hypr_rgb(theme.fg_muted),
        cfg.font,
        bottom_shadow
    )
end

return setmetatable(M, {
    __call = function(_, cfg, theme, layout)
        return M.emit(cfg, theme, layout)
    end,
})
