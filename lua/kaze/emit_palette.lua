local themes = require("kaze.themes")

local M = {}

local TOKENS = {
    "bg",
    "bg_alt",
    "surface",
    "border",
    "fg",
    "fg_muted",
    "accent",
    "accent_fg",
    "ok",
    "warn",
    "danger",
}

local function json_escape(s)
    return (tostring(s):gsub('[\\"%c]', function(c)
        if c == "\\" then return "\\\\" end
        if c == '"' then return '\\"' end
        if c == "\n" then return "\\n" end
        if c == "\r" then return "\\r" end
        if c == "\t" then return "\\t" end
        return string.format("\\u%04x", c:byte())
    end))
end

local function sh_quote(s)
    return "'" .. tostring(s):gsub("'", "'\\''") .. "'"
end

function M.emit(_cfg, theme, _layout)
    themes.validate(theme)
    local polarity = themes.is_light(theme) and "light" or "dark"
    local name = tostring(theme.name or "kaze")

    -- 1. ~/.cache/kaze/palette.lua (dofile-friendly read-only Lua table)
    local lua_lines = {
        "-- Auto-generated by kaze-sync — DO NOT EDIT MANUALLY (edit ~/.config/kaze/user.lua)",
        "return {",
        string.format("    name = %q,", name),
        string.format("    polarity = %q,", polarity),
    }
    for _, k in ipairs(TOKENS) do
        lua_lines[#lua_lines + 1] = string.format("    %s = %q,", k, "#" .. theme[k])
    end
    lua_lines[#lua_lines + 1] = "    raw = {"
    for _, k in ipairs(TOKENS) do
        lua_lines[#lua_lines + 1] = string.format("        %s = %q,", k, theme[k])
    end
    lua_lines[#lua_lines + 1] = "    },"
    if type(theme.term) == "table" and #theme.term == 16 then
        lua_lines[#lua_lines + 1] = "    term = {"
        for i = 1, 16 do
            lua_lines[#lua_lines + 1] = string.format("        %q,", "#" .. theme.term[i])
        end
        lua_lines[#lua_lines + 1] = "    },"
    end
    lua_lines[#lua_lines + 1] = "}"
    lua_lines[#lua_lines + 1] = ""

    -- 2. ~/.cache/kaze/palette.json (strict JSON for external scripts/editors)
    local json_colors = {}
    local json_raw = {}
    for _, k in ipairs(TOKENS) do
        json_colors[#json_colors + 1] = string.format('    "%s": "#%s"', k, theme[k])
        json_raw[#json_raw + 1] = string.format('    "%s": "%s"', k, theme[k])
    end
    local json_term = {}
    if type(theme.term) == "table" and #theme.term == 16 then
        for i = 1, 16 do
            json_term[#json_term + 1] = string.format('"#%s"', theme.term[i])
        end
    end
    local json_text = table.concat({
        '{"_generated":"Auto-generated by kaze-sync — DO NOT EDIT MANUALLY",',
        string.format('  "name": "%s",', json_escape(name)),
        string.format('  "polarity": "%s",', polarity),
        '  "colors": {',
        table.concat(json_colors, ",\n"),
        "  },",
        '  "raw": {',
        table.concat(json_raw, ",\n"),
        "  },",
        '  "term": [' .. table.concat(json_term, ", ") .. "]",
        "}",
        "",
    }, "\n")

    -- 3. ~/.cache/kaze/palette.sh (POSIX shell variables for tmux/zsh/fzf)
    local sh_lines = {
        "# Auto-generated by kaze-sync — DO NOT EDIT MANUALLY (edit ~/.config/kaze/user.lua)",
        "KAZE_THEME_NAME=" .. sh_quote(name),
        "KAZE_THEME_POLARITY=" .. sh_quote(polarity),
    }
    for _, k in ipairs(TOKENS) do
        sh_lines[#sh_lines + 1] = string.format("KAZE_%s=%s", k:upper(), sh_quote("#" .. theme[k]))
    end
    sh_lines[#sh_lines + 1] = ""

    return {
        lua = table.concat(lua_lines, "\n"),
        json = json_text,
        sh = table.concat(sh_lines, "\n"),
    }
end

return M
