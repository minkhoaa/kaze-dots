local themes = require("kaze.themes")

local M = {}

function M.emit_colors_css(_cfg, theme, _layout)
    return string.format([[/* Auto-generated by kaze-sync — DO NOT EDIT MANUALLY (edit ~/.config/kaze/user.lua) */
@define-color bg        %s;
@define-color bg_alt    %s;
@define-color surface   %s;
@define-color border    %s;
@define-color fg        %s;
@define-color fg_muted  %s;
@define-color accent    %s;
@define-color accent_fg %s;
@define-color ok        %s;
@define-color warn      %s;
@define-color danger    %s;
]],
        themes.hex(theme.bg),
        themes.hex(theme.bg_alt),
        themes.hex(theme.surface),
        themes.hex(theme.border),
        themes.hex(theme.fg),
        themes.hex(theme.fg_muted),
        themes.hex(theme.accent),
        themes.hex(theme.accent_fg),
        themes.hex(theme.ok),
        themes.hex(theme.warn),
        themes.hex(theme.danger)
    )
end

function M.emit_config_jsonc(cfg, theme, layout)
    assert(layout and type(layout.build_waybar_config) == "function",
        "emit_waybar: layout.build_waybar_config is required")
    return layout.build_waybar_config(cfg, theme)
end

function M.emit_style_css(cfg, theme, layout)
    assert(layout and type(layout.build_waybar_css) == "function",
        "emit_waybar: layout.build_waybar_css is required")
    return "/* Auto-generated by kaze-sync — DO NOT EDIT MANUALLY (edit ~/.config/kaze/user.lua) */\n"
        .. '@import "colors.css";\n\n'
        .. layout.build_waybar_css(cfg, theme)
end

function M.emit(cfg, theme, layout)
    return {
        colors_css = M.emit_colors_css(cfg, theme, layout),
        config_jsonc = M.emit_config_jsonc(cfg, theme, layout),
        style_css = M.emit_style_css(cfg, theme, layout),
    }
end

return setmetatable(M, {
    __call = function(_, cfg, theme, layout)
        return M.emit(cfg, theme, layout)
    end,
})
