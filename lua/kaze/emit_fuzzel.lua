local themes = require("kaze.themes")

local M = {}

function M.emit(cfg, theme, layout)
    local radius = layout.ui.fuzzel_radius
    local top_y = tonumber(layout.ui.popup_top_y) or 10
    local term = cfg.terminal
    if not term or term == "kaze-footclient" then
        term = "kaze-footclient -N"
    end
    local icon_theme = cfg.icon_theme or "hicolor"
    return string.format([[# Auto-generated by kaze-sync — DO NOT EDIT MANUALLY (edit ~/.config/kaze/user.lua)
[main]
font=%s Propo:size=11,%s:size=11
dpi-aware=no
use-bold=yes
terminal=%s
prompt="> "
icon-theme=%s
icons-enabled=yes
fields=filename,name,generic,keywords
anchor=top
y-margin=%d
width=40
lines=8
horizontal-pad=20
vertical-pad=16
inner-pad=12
line-height=26
image-size-ratio=0.45
layer=overlay
exit-on-keyboard-focus-loss=yes

[dmenu]
exit-immediately-if-empty=yes

[border]
width=1
radius=%d

[colors]
background=%s
text=%s
message=%s
prompt=%s
placeholder=%s
input=%s
match=%s
selection=%s
selection-text=%s
selection-match=%s
counter=%s
border=%s
]],
        cfg.font,
        cfg.font,
        term,
        icon_theme,
        top_y,
        radius,
        themes.hex_alpha(theme.bg_alt, "e8"),
        themes.hex_alpha(theme.fg, "ff"),
        themes.hex_alpha(theme.fg, "ff"),
        themes.hex_alpha(theme.accent, "ff"),
        themes.hex_alpha(theme.fg_muted, "ff"),
        themes.hex_alpha(theme.fg, "ff"),
        themes.hex_alpha(theme.accent, "ff"),
        themes.hex_alpha(theme.accent, "2e"),
        themes.hex_alpha(theme.fg, "ff"),
        themes.hex_alpha(theme.accent, "ff"),
        themes.hex_alpha(theme.fg_muted, "ff"),
        themes.hex_alpha(theme.border, "ff")
    )
end

return setmetatable(M, {
    __call = function(_, cfg, theme, layout)
        return M.emit(cfg, theme, layout)
    end,
})
