local fs = require("kaze.fs")

local M = {}

function M.path(config_dir)
    return (config_dir or fs.config_dir()) .. "/kaze/state.lua"
end

function M.load(path)
    local p = path or M.path()
    if not fs.file_exists(p) then
        return {}
    end
    local chunk, load_err = loadfile(p, "t", {})
    if not chunk then
        io.stderr:write(string.format("kaze warning: failed to parse state file %s: %s\n", p, tostring(load_err)))
        return {}
    end
    local ok, res = pcall(chunk)
    if not ok or type(res) ~= "table" then
        io.stderr:write(string.format("kaze warning: invalid state file %s: %s\n", p, tostring(res)))
        return {}
    end
    local out = {}
    if type(res.layout) == "string" and res.layout ~= "" then
        out.layout = res.layout
    end
    if type(res.theme) == "string" and res.theme ~= "" then
        out.theme = res.theme
    end
    return out
end

function M.save(tbl, path)
    assert(type(tbl) == "table", "state.save requires a table")
    local p = path or M.path()
    local lines = {
        "-- Auto-generated by kaze-dots — DO NOT EDIT MANUALLY",
        "return {",
    }
    if type(tbl.layout) == "string" and tbl.layout ~= "" then
        lines[#lines + 1] = string.format("    layout = %q,", tbl.layout)
    end
    if type(tbl.theme) == "string" and tbl.theme ~= "" then
        lines[#lines + 1] = string.format("    theme = %q,", tbl.theme)
    end
    lines[#lines + 1] = "}"
    lines[#lines + 1] = ""
    fs.write_atomic(p, table.concat(lines, "\n"))
    return p
end

return M
