#!/usr/bin/env bash
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
AUTO_YES=false

for arg in "$@"; do
    case "$arg" in
        --yes|-y)
            AUTO_YES=true
            ;;
        -h|--help)
            echo "Usage: $0 [--yes]"
            echo "Backs up existing configs, writes a reversible rollback.sh, symlinks kaze-dots into \$HOME, and runs kaze-sync."
            exit 0
            ;;
        *)
            echo "Unknown option: $arg" >&2
            exit 2
            ;;
    esac
done

if [ "$AUTO_YES" = false ]; then
    read -r -p "Apply kaze-dots symlinks and regenerate configs in $HOME? [y/N] " reply
    case "$reply" in
        [yY]|[yY][eE][sS]) ;;
        *)
            echo "Aborted."
            exit 1
            ;;
    esac
fi

DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
BIN_HOME="$HOME/.local/bin"

BASE_BACKUP="$CONFIG_HOME/.kaze-backup-$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$BASE_BACKUP"
suffix=2
while [ -e "$BACKUP_DIR" ]; do
    BACKUP_DIR="${BASE_BACKUP}-${suffix}"
    suffix=$((suffix + 1))
done

mkdir -p "$BACKUP_DIR/files" "$DATA_HOME/kaze-dots/lua" "$CONFIG_HOME/hypr" "$CONFIG_HOME/kaze" "$BIN_HOME"
INSTALLED_LIST="$BACKUP_DIR/installed.list"
BACKED_UP_LIST="$BACKUP_DIR/backed_up.list"
: > "$INSTALLED_LIST"
: > "$BACKED_UP_LIST"

record_installed() {
    local dst="$1"
    if ! grep -Fxq "$dst" "$INSTALLED_LIST" 2>/dev/null; then
        printf '%s\n' "$dst" >> "$INSTALLED_LIST"
    fi
}

backup_existing() {
    local dst="$1"
    if [ ! -e "$dst" ] && [ ! -L "$dst" ]; then
        return 0
    fi
    local rel="${dst#"$HOME"/}"
    if [ "$rel" = "$dst" ]; then
        rel="_abs/${dst#/}"
    fi
    local bdir="$BACKUP_DIR/files/$(dirname "$rel")"
    mkdir -p "$bdir"
    mv "$dst" "$BACKUP_DIR/files/$rel"
    printf '%s\t%s\n' "$rel" "$dst" >> "$BACKED_UP_LIST"
}

backup_and_link() {
    local src="$1"
    local dst="$2"
    mkdir -p "$(dirname "$dst")"
    record_installed "$dst"

    if [ -L "$dst" ] && [ "$(readlink -f "$dst" 2>/dev/null || true)" = "$(readlink -f "$src")" ]; then
        return 0
    fi

    backup_existing "$dst"
    ln -s "$src" "$dst"
}

backup_generated_if_custom() {
    local dst="$1"
    record_installed "$dst"
    if [ -L "$dst" ]; then
        backup_existing "$dst"
    elif [ -e "$dst" ] && ! grep -q "Auto-generated by kaze-sync" "$dst" 2>/dev/null; then
        backup_existing "$dst"
    fi
}

backup_and_link "$REPO_DIR/lua/kaze" "$DATA_HOME/kaze-dots/lua/kaze"

for f in hyprland.lua env.lua core.lua rules.lua execs.lua keybinds.lua; do
    backup_and_link "$REPO_DIR/hypr/$f" "$CONFIG_HOME/hypr/$f"
done

backup_and_link "$REPO_DIR/templates/hypridle.conf" "$CONFIG_HOME/hypr/hypridle.conf"

for bin_file in "$REPO_DIR"/bin/kaze-*; do
    chmod +x "$bin_file"
    backup_and_link "$bin_file" "$BIN_HOME/$(basename "$bin_file")"
done

for gen_file in \
    "$CONFIG_HOME/waybar/colors.css" \
    "$CONFIG_HOME/waybar/config.jsonc" \
    "$CONFIG_HOME/waybar/style.css" \
    "$CONFIG_HOME/foot/foot.ini" \
    "$CONFIG_HOME/fuzzel/fuzzel.ini" \
    "$CONFIG_HOME/fnott/fnott.ini" \
    "$CONFIG_HOME/hypr/hyprlock.conf"
do
    backup_generated_if_custom "$gen_file"
done

if [ ! -e "$CONFIG_HOME/kaze/user.lua" ]; then
    cp "$REPO_DIR/templates/user.lua.example" "$CONFIG_HOME/kaze/user.lua"
fi

cat <<'ROLLBACK_EOF' > "$BACKUP_DIR/rollback.sh"
#!/usr/bin/env bash
set -euo pipefail

BACKUP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AUTO_YES=false

for arg in "$@"; do
    case "$arg" in
        --yes|-y)
            AUTO_YES=true
            ;;
        -h|--help)
            echo "Usage: $0 [--yes]"
            echo "Removes kaze-dots symlinks/generated files and restores backed-up configs from $BACKUP_DIR."
            exit 0
            ;;
        *)
            echo "Unknown option: $arg" >&2
            exit 2
            ;;
    esac
done

if [ "$AUTO_YES" = false ]; then
    read -r -p "Rollback kaze-dots and restore configs from $BACKUP_DIR? [y/N] " reply
    case "$reply" in
        [yY]|[yY][eE][sS]) ;;
        *)
            echo "Aborted."
            exit 1
            ;;
    esac
fi

if [ -f "$BACKUP_DIR/installed.list" ]; then
    while IFS= read -r target; do
        [ -n "$target" ] || continue
        if [ -L "$target" ] || [ -f "$target" ]; then
            rm -f "$target"
        fi
    done < "$BACKUP_DIR/installed.list"
fi

if [ -f "$BACKUP_DIR/backed_up.list" ]; then
    while IFS=$'\t' read -r rel dst; do
        [ -n "$rel" ] && [ -n "$dst" ] || continue
        src="$BACKUP_DIR/files/$rel"
        if [ -e "$src" ] || [ -L "$src" ]; then
            mkdir -p "$(dirname "$dst")"
            if [ -e "$dst" ] || [ -L "$dst" ]; then
                rm -f "$dst"
            fi
            mv "$src" "$dst"
        fi
    done < "$BACKUP_DIR/backed_up.list"
fi

echo "Rolled back kaze-dots using $BACKUP_DIR (user.lua preserved)."
ROLLBACK_EOF
chmod +x "$BACKUP_DIR/rollback.sh"
printf '%s\n' "$BACKUP_DIR" > "$CONFIG_HOME/kaze/last-backup"

"$BIN_HOME/kaze-sync"

echo "Backup & rollback script: $BACKUP_DIR/rollback.sh"
echo "Applied kaze-dots cleanly."
